import Foundation
import XCTest
import LakeOfFireCore
import LakeOfFireContent
@testable import LakeOfFireReader

final class ReaderCaptionAcquisitionTests: XCTestCase {
    private let videoID = "abcdefghijk"
    private var frameURL: URL { URL(string: "https://www.youtube.com/watch?v=\(videoID)")! }
    private var owner: ReaderMediaPlaybackOwner {
        .init(canonicalContentURL: frameURL, resourceIdentity: ReaderMediaResourceIdentity.youtube(videoID),
              documentID: "document", playbackInstanceID: "player")
    }
    private func admitted(_ query: String = "v=abcdefghijk&lang=ja") -> ReaderValidatedCaptionRequest? {
        ReaderValidatedCaptionRequest.youtube(playbackOwner: owner, providerFrameURL: frameURL,
            claimedResourceID: videoID, subtitleURL: URL(string: "https://www.youtube.com/api/timedtext?" + query)!,
            languageIdentifier: "ja", isAutoGenerated: false)
    }

    func testProviderFrameResourceAndCaptionLanguageMustAgree() throws {
        let request = try XCTUnwrap(admitted())
        XCTAssertEqual(request.playbackOwner, owner)
        XCTAssertEqual(request.languageIdentifier, "ja")
        XCTAssertTrue(request.subtitleURL.absoluteString.hasSuffix("&fmt=vtt"))
        XCTAssertNil(admitted("v=differentID&lang=ja"))
        XCTAssertNil(admitted("v=abcdefghijk&lang=en"))
        let otherOwner = ReaderMediaPlaybackOwner(canonicalContentURL: frameURL,
            resourceIdentity: "url:https://example.com/unrelated", documentID: "document", playbackInstanceID: "player")
        XCTAssertNil(ReaderValidatedCaptionRequest.youtube(playbackOwner: otherOwner, providerFrameURL: frameURL,
            claimedResourceID: videoID, subtitleURL: request.subtitleURL, languageIdentifier: "ja", isAutoGenerated: false))
        XCTAssertNil(ReaderValidatedCaptionRequest.youtube(playbackOwner: owner,
            providerFrameURL: URL(string: "https://example.com/watch?v=abcdefghijk")!,
            claimedResourceID: videoID, subtitleURL: request.subtitleURL, languageIdentifier: "ja", isAutoGenerated: false))
    }

    func testDuplicateIdentityTranslationAndMismatchedCaptionKindAreRejected() {
        for query in ["v=abcdefghijk&v=abcdefghijk&lang=ja", "v=abcdefghijk&lang=ja&lang=ja",
                      "v=abcdefghijk&lang=ja&tlang=en", "v=abcdefghijk&lang=ja&TLANG=en",
                      "v=abcdefghijk&lang=ja&kind=asr", "v=abcdefghijk&lang=ja&fmt=vtt&fmt=vtt"] {
            XCTAssertNil(admitted(query), query)
        }
    }

    func testRedirectCannotChangeAdmittedHostResourceLanguageOrTransport() throws {
        let request = try XCTUnwrap(admitted())
        XCTAssertTrue(request.admits(request.subtitleURL))
        for value in ["http://www.youtube.com/api/timedtext?v=abcdefghijk&lang=ja&fmt=vtt",
                      "https://example.com/api/timedtext?v=abcdefghijk&lang=ja&fmt=vtt",
                      "https://www.youtube.com/api/timedtext?v=abcdefghijk&lang=en&fmt=vtt",
                      "https://user@www.youtube.com/api/timedtext?v=abcdefghijk&lang=ja&fmt=vtt"] {
            XCTAssertFalse(request.admits(URL(string: value)!))
        }
        XCTAssertNil(request.request.value(forHTTPHeaderField: "Cookie"))
        XCTAssertEqual(request.request.value(forHTTPHeaderField: "Accept"), "text/vtt")
    }

    func testHTTPResponseRequiresAcceptedStatusTypeEndpointAndBoundedLength() throws {
        let request = try XCTUnwrap(admitted())
        func response(_ status: Int = 200, type: String = "text/vtt", length: Int = 12,
                      url: URL? = nil) -> HTTPURLResponse {
            HTTPURLResponse(url: url ?? request.subtitleURL, statusCode: status,
                httpVersion: "HTTP/1.1", headerFields: ["Content-Type": type, "Content-Length": String(length)])!
        }
        XCTAssertNoThrow(try ReaderCaptionAcquisition.validateResponse(response(), for: request))
        XCTAssertThrowsError(try ReaderCaptionAcquisition.validateResponse(response(404), for: request)) {
            XCTAssertEqual($0 as? ReaderCaptionAcquisitionError, .httpStatus(404))
        }
        XCTAssertThrowsError(try ReaderCaptionAcquisition.validateResponse(response(type: "text/html"), for: request))
        XCTAssertThrowsError(try ReaderCaptionAcquisition.validateResponse(
            response(length: ReaderTranscriptDocument.maximumBytes + 1), for: request))
        XCTAssertThrowsError(try ReaderCaptionAcquisition.validateResponse(
            response(url: URL(string: "https://example.com/unrelated")!), for: request))
    }

    func testContentLanguageNormalizationDoesNotSubstituteDeviceLanguage() {
        XCTAssertEqual(ReaderTranscriptLanguage.normalizedIdentifier(nil), "und")
        XCTAssertEqual(ReaderTranscriptLanguage.normalizedIdentifier("  "), "und")
        XCTAssertEqual(ReaderTranscriptLanguage.normalizedIdentifier("ja_JP"), "ja-jp")
        XCTAssertEqual(ReaderTranscriptLanguage.normalizedIdentifier("en--US"), "und")
    }
}
